#include <iostream>
using namespace std;
int main()
{
    int day;
    cout<<"Enter your number :";
    cin>>day;
    if(day==0)
    {
        cout<<"sunday";
    }
    else if(day==1)
    {
        cout<<"monday";
    }
    else if(day==2)
    {
        cout<<"tuesday";
    }
    else if(day==3)
    {
        cout<<"wednesday";

    }
    else if(day==4)
    {
        cout<<"thrusday";
    }
    else if(day==5)
    {
        cout<<"friday";

    }
    else if(day==6)
    {
        cout<<"saturday";
    }
}